; scroll_text.s
; Scroll a banner across the LCD line

VRAM_BASE = $E000
SCROLL_LINE = $0080
SCROLL_SPEED = $000A

.org $0200

START:
    .byte $CF           ; Clear VRAM via CVR

    LDA #$00
    STA SCROLL_POS

SCROLL_LOOP:
    LDX #SCROLL_LINE
    JSR CLEAR_LINE
    JSR DISPLAY_SCROLL_TEXT

WAIT_LOOP:
    JSR DELAY
    DEX
    BNE WAIT_LOOP

    INC SCROLL_POS
    LDA SCROLL_POS
    CMP #MESSAGE_LENGTH
    BNE SCROLL_LOOP

    LDA #$00
    STA SCROLL_POS
    JMP SCROLL_LOOP

CLEAR_LINE:
    TXA
    JSR CALC_LINE_ADDR
    TAY
    LDX #60
    LDA #' '
CLEAR_LOOP:
    STA VRAM_BASE,Y
    INY
    DEX
    BNE CLEAR_LOOP
    RTS

DISPLAY_SCROLL_TEXT:
    LDA #SCROLL_LINE
    JSR CALC_LINE_ADDR
    TAY
    LDX SCROLL_POS
DISPLAY_LOOP:
    LDA MESSAGE,X
    BEQ DISPLAY_DONE
    STA VRAM_BASE,Y
    INY
    INX
    TYA
    AND #$3F
    CMP #60
    BCC DISPLAY_LOOP
DISPLAY_DONE:
    RTS

CALC_LINE_ADDR:
    STA $82
    ASL
    ASL
    STA $83
    LDA $82
    ASL
    ASL
    ASL
    ASL
    ASL
    ASL
    ASL
    SEC
    SBC $83
    RTS

DELAY:
    LDY #$FF
DELAY_LOOP:
    DEY
    BNE DELAY_LOOP
    RTS

SCROLL_POS:
    .byte $00

MESSAGE:
    .byte "*** TANG NANO 6502 CPU PROJECT *** "
    .byte "WELCOME TO FPGA WORLD! "
    .byte "THIS IS A COMPLETE 6502 IMPLEMENTATION "
    .byte "WITH LCD CONTROLLER ON TANG NANO FPGA BOARD. "
    .byte "ENJOY RETRO COMPUTING! *** ", $00

MESSAGE_LENGTH = * - MESSAGE - 1

CUSTOM_DEMO:
    .byte $DF
    .byte $FF
    RTS

.org $FFFC
.word START
